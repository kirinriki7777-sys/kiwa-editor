package dev.kirin.kiwa.settings

/**
 * 設定に打ち込む**識別子**（言語名・拡張子）を受ける形へ寄せる。画面を知らない。
 *
 * ## なぜ要るか ── 実機で「ご」が登録された（E7 の欠陥③）
 *
 * 設定のテキスト欄は IME を通る。日本語 IME が入った状態で `go` と打つと
 * **「ご」がそのまま登録された** ── 空でなければ受ける、という検査しか無かったため。
 * 登録されたものは拡張子の対応表に残り、**どの拡張子とも一致しないので色が付かない**。
 * 打った側からは「設定したのに効かない」としか見えない。
 *
 * ## 殴るだけに頼らない
 *
 * 欄には `IME_FLAG_FORCE_ASCII` を付けたが、**それが効くかは IME の実装次第**で、
 * この端末の Gboard で確かめるまで当てにできない（英語 subtype への切り替えが
 * 効かなかった前例もある）。だから**入ってきた文字の側でも受け止める**:
 *
 * - **全角の英数と記号は半角へ寄せる** ── `ｇｏ` は `go` のつもりで打たれている。
 *   パレットが全角の `＞` と `：` を prefix として受けたのと同じ考え方
 * - **それでも範囲外の文字が残ったら受けない** ── `ご` は寄せようが無い。
 *   ここで断らないと、効かない設定が黙って積まれる
 */
object Identifier {

    /** 言語名と拡張子に使う文字。`c++` / `f#` / `objective-c` / `.d.ts` が通る幅。 */
    private val ALLOWED: Set<Char> =
        (('a'..'z') + ('0'..'9') + listOf('+', '#', '.', '_', '-')).toSet()

    /**
     * 受ける形へ寄せる。**受けられなければ null。**
     *
     * 前後の空白を落とし、全角を半角へ寄せ、小文字にする。
     */
    fun normalize(raw: String): String? {
        val folded = buildString {
            for (ch in raw.trim()) append(halfWidth(ch))
        }.lowercase()
        if (folded.isEmpty()) return null
        if (!folded.all { it in ALLOWED }) return null
        return folded
    }

    /**
     * 全角を半角へ。**寄せられない文字はそのまま返す**（呼ぶ側が範囲で弾く）。
     *
     * 長音符（`ー`）を `-` に寄せているのは、日本語 IME で `-` を打つとこれが出るため。
     * 識別子に長音は入らないので、寄せて困る場面が無い。
     */
    private fun halfWidth(ch: Char): Char = when (ch) {
        in 'Ａ'..'Ｚ' -> 'A' + (ch - 'Ａ')
        in 'ａ'..'ｚ' -> 'a' + (ch - 'ａ')
        in '０'..'９' -> '0' + (ch - '０')
        '．' -> '.'
        '＋' -> '+'
        '＃' -> '#'
        '＿' -> '_'
        'ー', '－' -> '-'
        else -> ch
    }
}
