package dev.kirin.editoradapter;

import android.view.View;

/**
 * 編集エンジンの抽象。本体アプリは常にこの I/F 越しにエディタを触る。
 *
 * <p><b>なぜ挟むか。</b> 編集エンジンは自作しない方針で、現在の候補は Sora Editor。
 * ただし Sora は 0.x で内部設計の変更が続いており、Compose 版への移行も控えている。
 * エンジンの型がアプリ全体へ染み出すと、載せ替えのコストがアプリの規模に比例してしまう。
 * <b>この層に閉じ込めれば、載せ替えは実装1クラスの差し替えで済む。</b>
 *
 * <p><b>意図的に薄い。</b> 補完・診断・折りたたみ・整形・ミニマップは、
 * 境界の外側にある機能なのでここには出さない。ここが握るのは
 * <b>IME と物理キーボードが壊れないために必要なもの</b>だけ ── それが
 * 実機で測って分かった「エンジン任せにすると壊れる」範囲だから。
 *
 * <p><b>検索だけは例外で、別の I/F として隣に置いた</b>（{@link EditorSearch}）。
 * 外側の機能であることは変わらないが、<b>実装をアプリ側へ置けない</b> ──
 * エンジンが持っている検索を使う以上エンジンの型に触るコードが要り、
 * それを {@code :app} に置けないため（{@code tools/check-boundary.sh}）。
 * 本体に混ぜず {@link #search()} で取り出す形にしてあるので、
 * 検索を持たないエンジンへ載せ替えるときは<b>そこだけ差し替えられる</b>。
 *
 * <p><b>この I/F は特定のエンジンの型を1つも公開しない。</b>
 * {@code io.github.rosemoe} の import がこのモジュールに現れたら、その時点で
 * 差し替え可能性は失われている。{@code check-s6.sh} がそれを機械で検査する。
 */
public interface EditorEngine {

    /** 画面に載せるための View。実体はエンジンのビュー。 */
    View asView();

    // ------------------------------------------------------------------
    // テキスト
    // ------------------------------------------------------------------

    CharSequence getText();

    /**
     * テキスト全体を差し替える。
     *
     * <p><b>直後に編集してはいけない。</b> Sora 0.24.6 では、{@code setText()} の直後に
     * プログラムから {@code insert()} を呼ぶと落ちる ──
     * {@code LineBreakLayout.afterInsert}（widget/layout/LineBreakLayout.java:186）が
     * まだ空の内部リストを参照して {@code ArrayIndexOutOfBoundsException}。
     * 1フレーム空けると通ることを実機で確認した（S3b）。
     *
     * <p>人が打つ場合はフレームが挟まるので出ない。<b>流し込んだ直後に整形する、
     * テンプレートを差し込む、外部の編集を適用する</b>といった使い方で踏む。
     * エンジンを替えれば同じ罠があるとは限らないが、
     * 「設定した直後は編集できないことがある」は抽象として持っておく。
     */
    void setText(CharSequence text);

    /** 絶対インデックスから行・桁を得る。 */
    TextPosition positionOf(int index);

    /**
     * 範囲を置き換える。<b>Undo の1単位になる</b>（まとめて1回で戻る）。
     *
     * <p><b>なぜ {@link #setText(CharSequence)} で済まさないか。</b> 全文を差し替えると
     * Undo 履歴もスクロール位置も作り直しになる ── 行を1つ上へ動かしただけで
     * それまでの編集が戻せなくなる。行の操作（コメント・字下げ・行移動）は全部
     * 「範囲を置き換える」で書けるので、口はこれ1つでよい。
     *
     * <p><b>置き換えたあとに選択をどこへ置くかは呼び出し側が決める</b>
     * （{@link #setSelection(TextRange)}）。エンジンによって既定が違ううえ、
     * 「行を動かしたら選択も一緒に動く」のような意味づけは上の層のものだから。
     *
     * <p><b>Sora 0.24.6 での実装:</b> {@code Content.replace(...)} を
     * {@code beginBatchEdit()} / {@code endBatchEdit()} で挟む ── 挟まないと
     * 削除と挿入が別々の Undo 単位になり、戻すのに2回押すことになる。
     *
     * @param range       置き換える範囲。空なら挿入
     * @param replacement 入れる文字。空なら削除
     */
    void replaceRange(TextRange range, CharSequence replacement);

    /**
     * <b>キーボードで打ったのと同じ扱いで</b>カーソルの位置へ文字を入れる。
     * 括弧を自動で閉じる・選択を囲む、といった入力の決まりはエンジンと言語の既定に従う。
     *
     * <p><b>なぜ {@link #replaceRange} で済まさないか。</b> 置き換えは文字をそのまま書くので、
     * 入力の決まりを通らない ── 記号キー列の {@code (} だけが自動で閉じず、
     * 同じ場所で物理キーの {@code (} とは違う本文になる。
     * <b>決まりの中身（どの言語でどの組を閉じるか）をアプリへ写すと
     * 2箇所で食い違う</b>ので、打った文字の入口そのものを渡す口にした。
     *
     * <p>プログラムの都合で本文を書き換える操作（行の編集・置換・貼り付けの類）は
     * 今までどおり {@link #replaceRange} を使う。<b>こちらは人が1キー押した代わり</b>にだけ使う。
     *
     * <p><b>Undo の1単位になる</b>（閉じ括弧を足した場合も1回で戻る）。
     *
     * @param text 入れる文字。空なら何もしない
     */
    void typeText(CharSequence text);

    // ------------------------------------------------------------------
    // 文書（タブ）
    // ------------------------------------------------------------------

    /**
     * 文書を作る。<b>まだ画面には出さない</b>（出すのは {@link #showDocument}）。
     *
     * <p>作るのと出すのを分けてあるのは、<b>タブを開く操作が「作って出す」なのに対し、
     * タブを切り替える操作は「出すだけ」だから</b>。1つにすると切り替えのたびに
     * 文書が作り直され、{@link EditorDocument} が持っている Undo 履歴が消える。
     */
    EditorDocument newDocument(CharSequence text);

    /**
     * その文書を画面に出す。<b>切り替え前の文書のスクロール位置は覚えておき、
     * 戻ってきたときに復元する</b>（そこまでがエンジンの責務）。
     *
     * <p><b>なぜ位置の保存までここが持つか。</b> カーソルは文書が持っているが、
     * スクロール位置は「画面のどこを見ているか」なのでビューの側にある。
     * アプリに持たせると px を扱うことになり、
     * 「行・桁だけ知っていればいい」という上の層の前提が崩れる。
     */
    void showDocument(EditorDocument document);

    /**
     * その文書を捨てる（タブを閉じる）。<b>画面に出ている文書を捨てる場合は、
     * 先に別の文書を {@link #showDocument} してから呼ぶ</b>こと。
     *
     * <p>最後の1つを閉じたときに何を出すかは<b>アプリが決める</b>
     * ── 空の文書を作って出すのか、画面を閉じるのかは、エンジンの関心ではない。
     */
    void forgetDocument(EditorDocument document);

    /**
     * 中身かカーソルが変わったときに呼ばれるものを1つ登録する。{@code null} で外す。
     *
     * <p><b>前は足さないと決めていた口。</b> 未保存かどうかは「その場で全文を比較すれば分かる」ので、
     * 年に数えるほどしか呼ばない判定のために I/F を広げない、という判断だった。
     * <b>2026-09-06 の実機でその前提が崩れた</b> ── 状態表示（ファイル名・行桁・未保存）は
     * <b>打つたびに</b>変わるもので、押した時だけ描き直す形だと
     * 「1文字打っても未保存が出ない」になる。実際にそうなっていた。
     *
     * <p>だから足すのは「変わった」という合図だけで、<b>何が変わったかは渡さない</b> ──
     * 受け取る側は状態表示を描き直すだけなので、種類を知る必要が無い。
     * {@link Runnable} は標準型なので、この口からエンジンの型は出ない。
     */
    void setOnChangeListener(Runnable listener);

    /**
     * <b>新しく作る行</b>の改行コードを決める。{@code "\n"} / {@code "\r\n"} / {@code "\r"}。
     *
     * <p><b>なぜ要るか。</b> 既定のままだと、エンジンは開いたファイルの流儀に関係なく
     * 自分の既定（多くは LF）で行を足す。CRLF のファイルに1行書き足すと
     * <b>そのファイルだけ改行コードが混ざる</b> ── 実機で確認した（CRLF 3 + 単独 LF 1）。
     * 画面上は何も変わらないが、保存すると差分として出る。
     *
     * <p>読み込んだ側が「このファイルはどの流儀か」を知っているので、
     * <b>開いたときに呼ぶのは呼び出し側の責務</b>。
     * 文字コードと同じで、<b>推定して直すのではなく、元に合わせる</b>。
     */
    void setLineSeparator(String separator);

    // ------------------------------------------------------------------
    // カーソルと選択
    // ------------------------------------------------------------------

    /** 現在の選択範囲。選択が無ければ空の範囲（＝カーソル位置）。 */
    TextRange getSelection();

    void setSelection(TextRange range);

    // ------------------------------------------------------------------
    // Undo / Redo
    // ------------------------------------------------------------------

    /**
     * 元に戻せるか。
     *
     * <p>粒度は {@link ImeBoundary#beginCompositionScope()} が決める。
     * 変換1回が1単位になっているかは、エンジン任せでは保証されない。
     */
    boolean canUndo();

    void undo();

    boolean canRedo();

    void redo();

    // ------------------------------------------------------------------
    // 表示
    // ------------------------------------------------------------------

    /** 配色を切り替える。 */
    void setTheme(EditorTheme theme);

    /**
     * 構文ハイライトの言語を<b>名前で</b>指定する。{@code null} なら色を付けない。
     *
     * <p><b>なぜ名前だけか。</b> 文法の実体はエンジンごとに違う（Sora なら TextMate の
     * スコープ名と文法ファイル、別のエンジンなら Tree-sitter の言語オブジェクト）。
     * それをこの層の型にすると、載せ替えるたびに対応表を書き直すことになる ──
     * 配色（{@link EditorTheme}）と同じ理由で、<b>名前だけ通して解決はエンジンに任せる</b>。
     *
     * <p><b>知らない名前は黙って無視する</b>（色が付かないだけで、開けなくはならない）。
     * 呼び出し側は「この拡張子はこの言語」を持てばよく、
     * エンジンがその言語を持っているかは知らなくていい。
     *
     * <p>名前は小文字。エンジンが何を持っているかは<b>呼び出し側の関心ではない</b>ので、
     * ここに一覧は置かない ── 置くと増やすたびに2箇所を直すことになる。
     * 実際の対応は {@code tools/check-languages.sh} が
     * 「拡張子の表に在る名前」と「同梱している文法」の<b>集合が一致すること</b>で見ている。
     *
     * @param language 言語名。{@code null} で色を付けない
     */
    void setLanguage(String language);

    /**
     * 文字の大きさ（sp）。
     *
     * <p><b>sp で渡す。</b> 端末の文字サイズ設定に追従するのが Android の作法で、
     * エンジンが内部で px を要求するなら換算はエンジン側の仕事。
     * 呼び出し側が px を計算し始めると、端末を替えたときに合わなくなる。
     */
    void setTextSize(float sp);

    /**
     * 書体を<b>名前で</b>指定する。{@code "monospace"} / {@code "sans"} / {@code "serif"}。
     *
     * <p>{@link EditorTheme} や {@link #setLanguage(String)} と同じ扱い ──
     * 実体（{@code Typeface} なり別の型なり）はエンジンが持ち、この層は名前だけ通す。
     * <b>知らない名前は等幅へ落とす</b>（コードエディタなので、迷ったら等幅が安全）。
     */
    void setFont(String name);

    /**
     * インデントの幅と、タブ文字を使うかどうか。
     *
     * <p><b>2つを1回で渡すのは、片方だけ変えると必ずずれるから。</b> 幅8のタブを
     * 幅4のスペースへ切り替える途中の状態には意味が無い。
     *
     * <p><b>この設定はエンジンが保持する。</b> {@link #setLanguage(String)} で言語を
     * 替えても消えない ── エンジンによっては字下げの生成を言語オブジェクトが持っており
     * （Sora の {@code Language.useTab()}）、言語を作り直すと既定へ戻る。
     * <b>その復元はエンジン実装の責務</b>で、呼び出し側が言語のたびに呼び直す形にはしない
     * （呼び忘れが「設定したのに反映されない」になる）。
     *
     * @param width  1段の桁数。タブ文字の表示幅でもある
     * @param useTab true ならタブ文字、false ならスペース
     */
    void setIndent(int width, boolean useTab);

    /** 行番号を出すか。 */
    void setLineNumbersVisible(boolean visible);

    /** 空白・タブ・改行を目に見える印で描くか。 */
    void setShowInvisibles(boolean visible);

    /** カーソルのある行に地を敷くか。 */
    void setHighlightCurrentLine(boolean enabled);

    /**
     * 折り返しの有無。
     *
     * <p>エンジンによっては、折り返しの再計算が編集のたびに
     * 行テーブル全体を走査する（Sora 0.24.6 の {@code WordwrapLayout} は
     * 挿入位置以降の全行を触る ── widget/layout/WordwrapLayout.java:231）。
     *
     * <p><b>実機で測った結果（S3b / Redmi Pad 2 Pro）:</b> word wrap を有効にすると
     * 先頭への1文字挿入が行数にほぼ比例して遅くなる ──
     * <b>1,000行で 3.7ms / 5,000行で 13.1ms / 20,000行で 56.1ms</b>。
     * 20,000行は1フレーム（16.7ms）の3.4倍なので、打つたびに目に見えて引っかかる。
     * 無効なら行数に依らず 0.5〜1.1ms で、位置による差も無い。
     *
     * <p>したがって <b>行数によって切る</b>のがこの層の責務。実用上限は数千行。
     */
    void setWordWrap(boolean enabled);

    // ------------------------------------------------------------------
    // 一般的なエディタの設定（2026-10-02 に足した）
    //
    // どれも「エンジンが素で持っている振る舞いを入れる / 切る」だけで、
    // 新しい機能を境界に持ち込むものではない。既定値はエンジンの素の振る舞いに合わせてある
    // （足した日に見た目も打ち心地も変わらないように）。
    // ------------------------------------------------------------------

    /**
     * 行の高さ。<b>文字の高さに掛ける倍率</b>で渡す（1.0 で詰め、1.5 で半行ぶん空く）。
     *
     * <p>px の足し算で渡さないのは {@link #setTextSize(float)} と同じ理由 ──
     * 文字の大きさを変えたときに行間だけ取り残される。
     */
    void setLineSpacing(float multiplier);

    /** カーソルを点滅させるか。false なら出しっぱなし。 */
    void setCursorBlink(boolean enabled);

    /**
     * 開き括弧・引用符を打ったときに閉じる側を足すか。
     *
     * <p><b>どの組を閉じるかは言語とエンジンが決める</b>（{@link #typeText(CharSequence)} と同じ）。
     * ここは「閉じるかどうか」の1つだけを握る。空の組を Backspace で一緒に消す振る舞いも
     * 閉じた側の後始末なので、false なら一緒に止まる。
     */
    void setAutoClosePairs(boolean enabled);

    /** 改行したときに、前の行の字下げを引き継ぐか。 */
    void setAutoIndent(boolean enabled);

    /** カーソルの隣にある括弧と、その相手を強調するか。 */
    void setHighlightMatchingBrackets(boolean enabled);

    /**
     * 字下げの段に縦線（インデントガイド）を引くか。
     *
     * <p><b>線が引けるかは言語次第</b>（ブロックの範囲を言語が教えてくれる場合だけ出る）。
     * false にすれば必ず消える。
     */
    void setIndentGuides(boolean enabled);

    /**
     * 下へ送ったとき、いま居るブロックの頭の行を上に残す（固定見出し / sticky scroll）か。
     *
     * <p><b>折り返しが on の間は出ない</b>（エンジンが出さない）。false にすれば必ず消える。
     */
    void setStickyScroll(boolean enabled);

    /** 横へスクロールしたときに、行番号を左端へ留めておくか。 */
    void setPinLineNumbers(boolean pinned);

    // ------------------------------------------------------------------
    // IME 境界
    // ------------------------------------------------------------------

    /**
     * IME との境界。日本語入力が壊れないために握る必要があるものが、ここに集まっている。
     */
    ImeBoundary ime();

    // ------------------------------------------------------------------
    // 検索
    // ------------------------------------------------------------------

    /**
     * 本文の検索と置換。<b>この I/F は本体とは別物</b>（理由はクラスの Javadoc）。
     *
     * <p><b>同じ実体を返し続けること。</b> 呼ぶたびに作ると、
     * 登録した {@link EditorSearch#setOnResultListener(Runnable)} が
     * 前の実体に付いたまま黙って消える。
     */
    EditorSearch search();
}
